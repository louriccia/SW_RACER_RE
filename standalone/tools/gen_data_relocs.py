# Regenerates standalone/data_relocs.c: the dwords in retail .rdata/.data that hold pointers into the
# data range. Usage: python gen_data_relocs.py <SWEP1RCR.EXE> <data_symbols.syms> <out.c>
import struct, re, bisect, collections, sys
EXE = sys.argv[1]
SYMS = sys.argv[2]
b = open(EXE, 'rb').read()
pe = struct.unpack_from('<I', b, 0x3c)[0]; optsz = struct.unpack_from('<H', b, pe + 20)[0]
SECS = []
for i in range(struct.unpack_from('<H', b, pe + 6)[0]):
    o = pe + 24 + optsz + i * 40
    nm = b[o:o+8].rstrip(b'\0').decode(); vsz, va, rsz, rp = struct.unpack_from('<IIII', b, o + 8)
    SECS.append((nm, 0x400000 + va, vsz, rsz, rp))
TEXT = (0x401000, 0x4ac000); DATA = (0x4ac000, 0xece000); BSS = 0x4b2000 + 0x23600
def byte(va):
    for nm, v, vsz, rsz, rp in SECS:
        if v <= va < v + vsz:
            return b[rp + va - v] if va - v < rsz else 0
    return 0
def dword(va): return byte(va) | byte(va+1) << 8 | byte(va+2) << 16 | byte(va+3) << 24
syms = {}
for l in open(SYMS):
    m = re.match(r'(\w+) (0x[0-9a-fA-F]+)', l)
    if m: syms[int(m.group(2), 16)] = m.group(1)
keys = sorted(syms)
def name(a):
    i = bisect.bisect_right(keys, a) - 1
    return '%s+%x' % (syms[keys[i]], a - keys[i]) if i >= 0 else '?'
def is_strstart(v):
    return byte(v - 1) == 0 and all(32 <= byte(v + i) < 127 or byte(v + i) in (9, 10, 13) for i in range(2))
def textlike(a):
    bs = [byte(a + i) for i in range(4)]
    return all(x == 0 or 32 <= x < 127 for x in bs) and sum(32 <= x < 127 for x in bs) >= 2
def candidates():
    for nm, va, vsz, rsz, rp in SECS:
        if nm not in ('.rdata', '.data'): continue
        for off in range(0, min(vsz, rsz) - 3, 4):
            a = va + off; v = dword(a)
            if DATA[0] <= v < DATA[1]: yield a, v
BLOBS = ('swrPlayerHUD_lightStreakParam', 'stdMath_TanTable', 'Window_UUID', 'swrMusicTrackTable', 'swrObjElmo_animFramesC3po')
acc = []; why = collections.Counter()
for a, v in candidates():
    region = name(a).split('+')[0]
    if is_strstart(v): k = 'string'
    elif textlike(a):
        if v % 4 == 0 and v < BSS and byte(a - 1) == 0: k = 'table-printable'
        else: continue
    elif v >= BSS and v % 4: continue
    elif v in syms: k = 'symbol'
    elif v % 4: continue
    elif v < BSS: k = 'init'
    elif region in BLOBS: continue
    else: k = 'bss'
    acc.append((a, v)); why[k] += 1
print(why, len(acc))
# Dwords that may hold a retail code address. The loader only rewrites the ones whose value is the
# entry of a function it has a body for (or a .text global it owns), so false positives stay put.
code = []
for nm, va, vsz, rsz, rp in SECS:
    if nm not in ('.rdata', '.data'): continue
    for off in range(0, min(vsz, rsz) - 3, 4):
        a = va + off; v = dword(a)
        if TEXT[0] <= v < TEXT[1]: code.append(a)
print('code pointer candidates', len(code))
with open(sys.argv[3], 'w') as f:
    f.write('// Generated by standalone/tools/gen_data_relocs.py from SWEP1RCR.EXE: every dword in retail\n')
    f.write('// .rdata/.data that holds a pointer into the data range. The standalone relocates these when it\n')
    f.write('// moves the data image away from 0x4ac000.\n#include <stdint.h>\n\n')
    f.write('const uint32_t standalone_data_relocs[] = {\n')
    for i in range(0, len(acc), 8):
        f.write('    ' + ', '.join('0x%08x' % a for a, v in acc[i:i+8]) + ',\n')
    f.write('};\nconst int standalone_data_reloc_count = %d;\n' % len(acc))
    f.write('\n// Dwords that may hold a retail code address (see standalone_relocate_code_pointers).\n')
    f.write('const uint32_t standalone_code_relocs[] = {\n')
    for i in range(0, len(code), 8):
        f.write('    ' + ', '.join('0x%08x' % a for a in code[i:i+8]) + ',\n')
    f.write('};\nconst int standalone_code_reloc_count = %d;\n' % len(code))
