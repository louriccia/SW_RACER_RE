# Owned globals for the standalone: retail globals get storage of their own instead of living at
# their retail address in the data image.
#
# Step 1 (sizes): python gen_owned_globals.py sizes <globals.h> <out.c>
#   writes a program that prints "name address sizeof" for every global in globals.h.
# Step 2 (owned): python gen_owned_globals.py owned <globals.h> <sizes.txt> <owned_extents.txt> <out.h> <out.c>
#   writes globals_owned.h (redirects the names to their storage) and globals_owned.c (the storage
#   and the table the loader fills it from).
#
# Every named global in the data range gets storage covering its retail footprint, up to the next
# named global, so a type smaller than the bytes the code really uses (DirectInputJoysticks is a
# void* but holds eight device records) still lands in the same storage. Overlapping names share
# one block. A global whose type exactly fills its footprint becomes a plain variable of that type.
# Only bytes before the first named global stay in the retail image.
import re
import sys

TEXT_LO, DATA_LO, DATA_HI = 0x00401000, 0x004AC000, 0x00ECE000
MACRO = re.compile(r'#define (\w+) \(\*\((.*)\)SWR_IMAGE_PTR\((0x[0-9a-fA-F]+)\)\)\s*$')
# Names the Windows SDK already declares (GUIDs, DirectInput formats) cannot be plain variables.
SDK_NAME = re.compile(r'^(IID_|CLSID_|GUID_|DIPROP_|c_df)')
NL = chr(92) + 'n'


def read_globals(path):
    out = []
    for line in open(path, encoding='ascii'):
        m = MACRO.match(line)
        if m:
            out.append((m.group(1), m.group(2), int(m.group(3), 16)))
    return out


def unsized(ptr_type):
    return '(*)[]' in ptr_type.replace(' ', '')


def write_sizes(globals_h, out_c):
    g = read_globals(globals_h)
    lines = ['#include <stdio.h>', '#include "globals.h"', '', 'static const unsigned table[][2] = {']
    for name, ptr_type, addr in g:
        lines.append('    {0x%08x, %s},' % (addr, '0' if unsized(ptr_type) else 'sizeof(%s)' % name))
    lines.append('};')
    lines.append('static const char* names[] = {')
    for name, ptr_type, addr in g:
        lines.append('    "%s",' % name)
    lines.append('};')
    lines.append('')
    lines.append('int main(void)')
    lines.append('{')
    lines.append('    for (unsigned i = 0; i < sizeof(table) / sizeof(table[0]); i++)')
    lines.append('        printf("%s %08x %u' + NL + '", names[i], table[i][0], table[i][1]);')
    lines.append('    return 0;')
    lines.append('}')
    open(out_c, 'w', encoding='ascii').write('\n'.join(lines) + '\n')


def storage_groups(g, sizes):
    rows = sorted((addr, sizes[name][0], name, ptr_type) for name, ptr_type, addr in g if name in sizes)
    rows = [r for r in rows if TEXT_LO <= r[0] < DATA_HI]
    groups = []
    end = 0
    for addr, size, name, ptr_type in rows:
        if groups and addr < end:
            groups[-1]['names'].append((addr, size, name, ptr_type))
            end = max(end, addr + max(size, 1))
        else:
            groups.append({'start': addr, 'names': [(addr, size, name, ptr_type)]})
            end = addr + max(size, 1)
    for i, grp in enumerate(groups):
        if grp['start'] < DATA_LO:
            # data dinput.lib linked into retail .text (stdControl_df*): just the object itself
            grp['extent'] = max(max(n[0] + n[1] for n in grp['names']) - grp['start'], 1)
            continue
        grp['extent'] = (groups[i + 1]['start'] if i + 1 < len(groups) else DATA_HI) - grp['start']
    return groups


CANARY = 32  # poisoned bytes after each storage block; the loader reports any that change


def read_extents(path):
    out = {}
    for line in open(path):
        line = line.split('#')[0].split()
        if len(line) == 2:
            out[line[0]] = int(line[1], 16)
    return out


def write_owned(globals_h, sizes_txt, extents_txt, out_h, out_c, guarded=False):
    g = read_globals(globals_h)
    sizes = {}
    for line in open(sizes_txt):
        name, addr, size = line.split()
        sizes[name] = (int(size), int(addr, 16))
    for name, extent in read_extents(extents_txt).items():
        if name in sizes:
            sizes[name] = (max(sizes[name][0], extent), sizes[name][1])
    groups = storage_groups(g, sizes)
    h = ['// Generated by standalone/tools/gen_owned_globals.py. Included by globals.h when',
         '// SWR_GLOBALS_OWNED: retail globals live in storage of their own, not at retail addresses.',
         '#ifndef GLOBALS_OWNED_H', '#define GLOBALS_OWNED_H', '', '#ifdef __cplusplus', 'extern "C" {', '#endif', '',
         'extern unsigned char* swr_owned_ptr[];', '']
    c = ['// Generated by standalone/tools/gen_owned_globals.py: storage for the owned globals and the',
         '// table the standalone loader fills it from (retail address, storage, footprint).',
         '#include "globals.h"', '#include "standalone_owned.h"', '']
    table = []
    typed = 0
    # This file is compiled with -fno-toplevel-reorder, so each canary directly follows its block.
    # Guarded (diagnostic) builds instead reach every block through swr_owned_ptr, which the loader
    # points at storage that ends right before an inaccessible page.
    for i, grp in enumerate(groups):
        addr, size, name, ptr_type = grp['names'][0]
        canary = 'swr_canary_%d' % i
        if guarded:
            for a, sz, n, t in grp['names']:
                h.append('#undef %s' % n)
                h.append('#define %s (*(%s)(swr_owned_ptr[%d] + 0x%x))' % (n, t, i, a - grp['start']))
            table.append((grp['start'], '0', grp['extent'], name, '0'))
            continue
        if len(grp['names']) == 1 and size == grp['extent'] and not SDK_NAME.match(name):
            h.append('#undef %s' % name)
            h.append('extern __typeof__(*(%s)0) %s; // 0x%08x' % (ptr_type, name, addr))
            c.append('__typeof__(*(%s)0) %s;' % (ptr_type, name))
            c.append('unsigned char %s[%d];' % (canary, CANARY))
            table.append((grp['start'], '&' + name, grp['extent'], name, canary))
            typed += 1
            continue
        block = 'swr_own_' + name
        h.append('extern unsigned char %s[0x%x]; // 0x%08x' % (block, grp['extent'], grp['start']))
        c.append('__attribute__((aligned(16))) unsigned char %s[0x%x];' % (block, grp['extent']))
        c.append('unsigned char %s[%d];' % (canary, CANARY))
        for a, sz, n, t in grp['names']:
            h.append('#undef %s' % n)
            h.append('#define %s (*(%s)(%s + 0x%x))' % (n, t, block, a - grp['start']))
        table.append((grp['start'], block, grp['extent'], name, canary))
    h += ['', '#ifdef __cplusplus', '}', '#endif', '', '#endif']
    c.append('')
    c.append('unsigned char* swr_owned_ptr[%d];' % len(groups))
    c.append('const int standalone_owned_guarded = %d;' % (1 if guarded else 0))
    c.append('StandaloneOwnedGlobal standalone_owned_globals[] = {')
    for start, ptr, extent, name, canary in table:
        c.append('    {0x%08x, (void*)%s, 0x%x, "%s", (unsigned char*)%s},' % (start, ptr, extent, name, canary))
    c.append('};')
    c.append('const int standalone_owned_global_count = %d;' % len(table))
    c.append('const int standalone_owned_canary_size = %d;' % CANARY)
    open(out_h, 'w', encoding='ascii').write('\n'.join(h) + '\n')
    open(out_c, 'w', encoding='ascii').write('\n'.join(c) + '\n')
    named = sum(len(grp['names']) for grp in groups)
    print('%d storage groups for %d named globals (%d plain typed variables) of %d' % (len(groups), named, typed, len(g)))


if __name__ == '__main__':
    if sys.argv[1] == 'sizes':
        write_sizes(sys.argv[2], sys.argv[3])
    else:
        write_owned(sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5], sys.argv[6],
                    len(sys.argv) > 7 and sys.argv[7] == 'guarded')
